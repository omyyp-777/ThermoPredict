-- Run this in Supabase Dashboard -> SQL Editor -> New query.
create table if not exists public.telemetry (
  id bigint generated by default as identity primary key,
  device_id text not null check (char_length(device_id) between 1 and 64),
  "timestamp" timestamptz not null,
  exterior_wall_temp_c double precision not null check (exterior_wall_temp_c between -50 and 100),
  interior_wall_temp_c double precision not null check (interior_wall_temp_c between -50 and 100),
  room_temp_c double precision not null check (room_temp_c between -20 and 80),
  humidity_pct double precision not null check (humidity_pct between 0 and 100),
  created_at timestamptz not null default now()
);
create index if not exists telemetry_device_timestamp_idx
  on public.telemetry (device_id, "timestamp" desc);

-- Keep Row Level Security enabled. Backend accesses the table with the service-role key,
-- which must remain only in Render environment variables and never in frontend or firmware.
alter table public.telemetry enable row level security;
